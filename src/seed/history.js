const rng = (seed) => () => {
  seed |= 0; seed = (seed + 0x6d2b79f5) | 0
  let t = Math.imul(seed ^ (seed >>> 15), 1 | seed)
  t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t
  return ((t ^ (t >>> 14)) >>> 0) / 4294967296
}

export const schoolYearStart = (now = new Date()) => new Date(now.getMonth() >= 7 ? now.getFullYear() : now.getFullYear() - 1, 8, 1)

const DAY = 864e5
const school = (rand, base) => new Date(base.getTime() + (8 + rand() * 8) * 36e5) // 8:00–16:00

/**
 * names — список учеников. Возвращает всё, что нужно записать в базу:
 * ссылки на учеников — по индексу в names.
 */
export function buildHistory({ names = DEFAULT_NAMES, now = new Date(), seed = 70 } = {}) {
  const rand = rng(seed)
  const start = schoolYearStart(now)
  const pick = (a) => a[Math.floor(rand() * a.length)]
  const n = names.length
  const stations = STATIONS.map((s) => ({ ...s }))
  const LAST = stations.length - 1

  // недели: поезд едет один перегон в неделю
  const weeksPassed = Math.max(0, Math.floor((now - start) / (7 * DAY)))
  const idx = Math.min(weeksPassed, LAST)

  const fives = []
  const legs = []
  const pushedAt = new Set(idx >= 5 ? [2, 4] : idx >= 3 ? [2] : [])   // какие перегоны «дотолкали»
  for (let k = 0; k < idx; k++) {
    const weekStart = start.getTime() + k * 7 * DAY
    const pushed = pushedAt.has(k)
    const total = pushed ? 41 + Math.floor(rand() * 12) : 60 + Math.floor(rand() * 5)
    const rows = []
    let left = total
    // пару раз за неделю учитель вписывает пятёрки за контрольные пачкой
    for (const bulk of [Math.floor(rand() * 6) + 6, Math.floor(rand() * 5) + 4]) {
      if (left <= bulk + 5) continue
      rows.push({ who: 'teacher', subject: pick(['Контрольная по математике', 'Диктант', 'Проверочная по истории', 'Тест по биологии']), count: bulk, at: school(rand, new Date(weekStart + (1 + Math.floor(rand() * 4)) * DAY)) })
      left -= bulk
    }
    for (let i = 0; i < left; i++) {
      const day = Math.floor(rand() * 6)                    // пн–сб
      rows.push({ who: Math.floor(rand() * n), subject: pick(SUBJECTS), count: 1, at: school(rand, new Date(weekStart + day * DAY)) })
    }
    rows.sort((a, b) => a.at - b.at)
    fives.push(...rows.map((r) => ({ ...r, week: k })))
    const last = rows[rows.length - 1].at
    legs.push({
      idx: k + 1, station: stations[k + 1], pushed, fives_total: total,
      arrived_at: pushed ? new Date(weekStart + 7 * DAY - 1) : last,
    })
  }
  // текущая неделя — пятёрки ещё набираются
  if (idx <= LAST) {
    const weekStart = start.getTime() + idx * 7 * DAY
    const elapsed = Math.max(0, Math.min(1, (now - weekStart) / (7 * DAY)))
    const total = Math.round(elapsed * 52)
    for (let i = 0; i < total; i++) {
      const at = new Date(weekStart + (i / Math.max(1, total)) * (now - weekStart))
      fives.push({ who: Math.floor(rand() * n), subject: pick(SUBJECTS), count: 1, at, week: idx })
    }
  }

  // добрые дела: ~ 1–2 в день, с равномерным темпом с сентября
  const nDeeds = Math.min(DEEDS.length, Math.max(8, Math.round(((now - start) / DAY) * 1.4)))
  const titles = [...DEEDS].sort(() => rand() - 0.5).slice(0, nDeeds)
  const deeds = titles.map((title, i) => {
    const t = start.getTime() + ((i + rand() * 0.8) / nDeeds) * (now - start - 3600e3)
    return { who: Math.floor(rand() * n), tree: pick(TREES), title, at: school(rand, new Date(Math.floor(t / DAY) * DAY)) }
  }).sort((a, b) => a.at - b.at).map((d) => ({ ...d, at: d.at > now ? new Date(now - 36e5) : d.at }))

  // книги
  const nBooks = Math.min(BOOKS.length, Math.max(4, Math.round(((now - start) / DAY) * 0.6)))
  const books = [...BOOKS].sort(() => rand() - 0.5).slice(0, nBooks).map(([title, author, genre, stars, review], i) => ({
    who: Math.floor(rand() * n), title, author, genre, stars, review, color: pick(COLORS),
    at: school(rand, new Date(Math.floor((start.getTime() + ((i + 0.5) / nBooks) * (now - start - 86400e3)) / DAY) * DAY)),
  })).sort((a, b) => a.at - b.at)

  // письма в ящик — от «призраков»: никто из реальных учеников не получит чужие письма в «Мои письма»
  const worries = WORRIES.map(([text, mood, size, reply], i) => {
    const created = school(rand, new Date(start.getTime() + (5 + i * 5.6 + rand() * 2) * DAY))
    const ok = created < now - 36e5
    return ok ? { text, mood, size, at: created, reply: reply || null, replied_at: reply ? new Date(created.getTime() + (10 + rand() * 20) * 36e5) : null } : null
  }).filter(Boolean)

  return { names, stations, idx, fives, legs, deeds, books, worries, start }
}
